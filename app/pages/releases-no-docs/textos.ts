/** Data por extenso no idioma da tela. UTC fixo: a data não anda 1 dia para trás pelo fuso. */
export function formatarData(iso: string, idioma: Idioma, opcoes: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long' }) {
  return new Date(`${iso}T12:00:00Z`).toLocaleDateString(idioma, { ...opcoes, timeZone: 'UTC' })
}
